  static getShapesBySection(section: string): InteractiveCutShape[] {
    if (section === 'all') return this.ALL_SHAPES;
    return this.ALL_SHAPES.filter(s => s.section === section);
  }

  static getShapesByCategory(category: string): InteractiveCutShape[] {
    if (category === 'all') return this.ALL_SHAPES;
    return this.ALL_SHAPES.filter(s => s.category === category);
  }

  static getShape(id: string): InteractiveCutShape | undefined {
    return this.ALL_SHAPES.find(s => s.id === id);
  }
